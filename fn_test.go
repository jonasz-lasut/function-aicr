func TestParseOverrides(t *testing.T) {
	raw := func(j string) *runtime.RawExtension { return &runtime.RawExtension{Raw: []byte(j)} }

	type args struct {
		in *v1beta1.Input
	}
	type want struct {
		overrides map[string]*compose.Override
		err       error
	}

	cases := map[string]struct {
		reason string
		args   args
		want   want
	}{
		"ObjectValues": {
			reason: "A JSON object becomes the override's values; version and namespace pass through.",
			args: args{in: &v1beta1.Input{ComponentOverrides: map[string]v1beta1.ComponentOverride{
				"gpu-operator": {Version: "v99.0.0", Namespace: "gpu", Values: raw(`{"driver":{"enabled":false}}`)},
			}}},
			want: want{overrides: map[string]*compose.Override{
				"gpu-operator": {Version: "v99.0.0", Namespace: "gpu", Values: map[string]any{"driver": map[string]any{"enabled": false}}},
			}},
		},
		"NoValues": {
			reason: "An override without values customizes only version and namespace.",
			args: args{in: &v1beta1.Input{ComponentOverrides: map[string]v1beta1.ComponentOverride{
				"cert-manager": {Namespace: "certs"},
			}}},
			want: want{overrides: map[string]*compose.Override{"cert-manager": {Namespace: "certs"}}},
		},
		"NullValues": {
			reason: "A JSON null is the same as no values.",
			args: args{in: &v1beta1.Input{ComponentOverrides: map[string]v1beta1.ComponentOverride{
				"cert-manager": {Values: raw(`null`)},
			}}},
			want: want{overrides: map[string]*compose.Override{"cert-manager": {}}},
		},
		"NonObjectValuesError": {
			reason: "Values that are valid JSON but not an object are rejected rather than dropped.",
			args: args{in: &v1beta1.Input{ComponentOverrides: map[string]v1beta1.ComponentOverride{
				"gpu-operator": {Values: raw(`["a","b"]`)},
			}}},
			want: want{err: cmpopts.AnyError},
		},
		"MalformedValuesError": {
			reason: "Values that are not JSON at all are rejected up front.",
			args: args{in: &v1beta1.Input{ComponentOverrides: map[string]v1beta1.ComponentOverride{
				"gpu-operator": {Values: raw(`{driver:`)},
			}}},
			want: want{err: cmpopts.AnyError},
		},
	}

	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			got, err := parseOverrides(tc.args.in)
			if diff := cmp.Diff(tc.want.err, err, cmpopts.EquateErrors()); diff != "" {
				t.Errorf("%s\nparseOverrides(...): -want err, +got err:\n%s", tc.reason, diff)
			}
			if diff := cmp.Diff(tc.want.overrides, got); diff != "" {
				t.Errorf("%s\nparseOverrides(...): -want, +got:\n%s", tc.reason, diff)
			}
		})
	}
}

