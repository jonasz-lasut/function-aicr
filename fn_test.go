// TestCatalogInvariants resolves every leaf recipe of the embedded AICR
// catalog through the function's own building blocks and asserts the
// properties the function relies on but TestRunFunction — which pins the
// content of a single, manifest-free tier — cannot see. An AICR bump that ships
// a manifest that does not render, two documents that map to the same Object
// name, a disabled component in the deployment order, a dependency on a
// component that is not in the recipe, or a dependency graph the gate can
// never drain fails here, not in a cluster.
func TestCatalogInvariants(t *testing.T) {
	ctx := context.Background()
	dp := embeddedDataProvider()

	leaves, err := recipe.ResolveLeaves(ctx, recipe.ResolveLeavesOptions{Provider: dp, Version: testRecipeVersion})
	if err != nil {
		t.Fatalf("recipe.ResolveLeaves(...): %v", err)
	}
	if len(leaves) == 0 {
		t.Fatal("recipe.ResolveLeaves(...): the embedded catalog has no leaf recipes")
	}

	pcRef := compose.ProviderConfigRef{Kind: "ClusterProviderConfig", Name: "gpu-cluster"}
	permissive, err := schema.NewValidator(permissiveSchema().GetOpenapiV3())
	if err != nil {
		t.Fatalf("schema.NewValidator(...): %v", err)
	}

	for _, leaf := range leaves {
		t.Run(leaf.Entry.Name, func(t *testing.T) {
			t.Parallel()
			if leaf.Err != nil {
				t.Fatalf("the catalog cannot resolve this leaf: %v", leaf.Err)
			}
			criteria := leaf.Entry.Criteria
			if err := criteria.Validate(); err != nil {
				t.Fatalf("a shipped leaf's criteria must pass AICR's own validation, or the function could never resolve it: %v", err)
			}

			// The function's own resolution path, without a snapshot evaluator.
			res, err := recipe.NewBuilder(recipe.WithVersion(testRecipeVersion), recipe.WithDataProvider(dp)).BuildFromCriteria(ctx, criteria)
			if err != nil {
				t.Fatalf("BuildFromCriteria(%s): %v", criteria, err)
			}

			rsp := &fnv1.RunFunctionResponse{}
			managed := managedComponents(rsp, res, &v1beta1.Input{})
			for _, r := range rsp.GetResults() {
				if r.GetSeverity() == fnv1.Severity_SEVERITY_WARNING {
					t.Errorf("managedComponents(...) warned with no skips or overrides configured: %s", r.GetMessage())
				}
			}
			if len(managed) == 0 {
				t.Fatalf("no managed component: the leaf would deploy nothing")
			}

			inRecipe := make(map[string]bool, len(res.ComponentRefs))
			enabled := make(map[string]bool, len(res.ComponentRefs))
			for _, c := range res.ComponentRefs {
				inRecipe[c.Name] = true
				enabled[c.Name] = c.IsEnabled()
			}
			ordered := make(map[string]bool, len(res.DeploymentOrder))
			for _, name := range res.DeploymentOrder {
				ordered[name] = true
				if !enabled[name] {
					t.Errorf("DeploymentOrder lists %q, which is disabled or absent; the summary would report a component the function never deploys", name)
				}
			}
			for _, name := range slices.Sorted(maps.Keys(managed)) {
				if !ordered[name] {
					t.Errorf("managed component %q is not in DeploymentOrder — is it disabled by the recipe?", name)
				}
			}
			for _, name := range slices.Sorted(maps.Keys(managed)) {
				for _, dep := range managed[name].DependencyRefs {
					if !inRecipe[dep] {
						t.Errorf("%q depends on %q, which is not a component of the recipe", name, dep)
					}
				}
			}

			values, err := resolveValues(ctx, res, managed)
			if err != nil {
				t.Fatalf("resolveValues(...): %v", err)
			}

			// Every Release must build and every manifest file must render
			// and parse — the function is Fatal otherwise, and a recipe with
			// a Fatal tier is unusable.
			s := &stack{
				managed:       managed,
				values:        values,
				pcRef:         pcRef,
				dp:            dp,
				releaseSchema: permissive,
				objectSchema:  permissive,
				desired:       make(map[resource.Name]*resource.DesiredComposed),
			}
			if err := s.composeReleases(); err != nil {
				t.Fatalf("composeReleases(): %v", err)
			}
			if err := s.composeObjects(ctx); err != nil {
				t.Fatalf("composeObjects(...): %v", err)
			}
			releases, emitted := 0, 0
			for _, name := range slices.Sorted(maps.Keys(managed)) {
				if !managed[name].IsManifestOnlyHelm() {
					releases++
				}
				emitted += len(s.objects.all(name))
			}
			all := s.desired
			if releases+emitted != len(all) {
				t.Errorf("names collide: %d Releases and %d Objects composed but %d distinct names; a later resource overwrote an earlier one", releases, emitted, len(all))
			}

			// The gate must eventually emit everything: starting from nothing
			// observed, and marking whatever it emits Ready between rounds,
			// the withheld set must reach zero. A dependency graph it cannot
			// drain — the manifest-only deadlock class — shows up as
			// resources it never emits.
			total := len(all)
			observed := make(map[resource.Name]resource.ObservedComposed, total)
			converged := false
			for round := 0; round <= 3*len(managed)+3; round++ {
				d := maps.Clone(all)
				(&stack{managed: managed, desired: d, observed: observed, objects: s.objects}).gate(&fnv1.RunFunctionResponse{})
				if len(d) == total {
					converged = true
					break
				}
				progressed := false
				for name := range d {
					if _, ok := observed[name]; ok {
						continue
					}
					cd := composed.New()
					cd.SetName(string(name))
					cd.SetConditions(xpv2.Available())
					observed[name] = resource.ObservedComposed{Resource: cd}
					progressed = true
				}
				if !progressed {
					break
				}
			}
			if !converged {
				never := make([]string, 0)
				for name := range all {
					if _, ok := observed[name]; !ok {
						never = append(never, string(name))
					}
				}
				slices.Sort(never)
				t.Errorf("the gate never emits %d of %d resources even with everything it emitted Ready — a dependency it can never see satisfied: %v", len(never), total, never)
			}
		})
	}
}

// TestGate exercises the gate directly. The embedded "kind" recipe used by
// TestRunFunction carries no manifest files, and its gate cases only ever place
// the dependency (cert-manager) in observed, never the dependent itself; so
// neither the pre-/post-manifest waves nor the "never gate something already
// created" guards have coverage there. The gate withholds resources by deleting
// map entries from desired, which is authoritative — untested deletion logic
// can silently tear down a running component.
func TestGate(t *testing.T) {
	observedResource := func(name string, ready bool) (resource.Name, resource.ObservedComposed) {
		cd := composed.New()
		cd.SetName(name)
		if ready {
			cd.SetConditions(xpv2.Available())
		}
		return resource.Name(name), resource.ObservedComposed{Resource: cd}
	}
	observe := func(entries ...func() (resource.Name, resource.ObservedComposed)) map[resource.Name]resource.ObservedComposed {
		observed := make(map[resource.Name]resource.ObservedComposed, len(entries))
		for _, e := range entries {
			name, oc := e()
			observed[name] = oc
		}
		return observed
	}
	ready := func(name string) func() (resource.Name, resource.ObservedComposed) {
		return func() (resource.Name, resource.ObservedComposed) { return observedResource(name, true) }
	}
	notReady := func(name string) func() (resource.Name, resource.ObservedComposed) {
		return func() (resource.Name, resource.ObservedComposed) { return observedResource(name, false) }
	}
	delay := func(format string, a ...any) *fnv1.Result {
		return &fnv1.Result{
			Severity: fnv1.Severity_SEVERITY_NORMAL,
			Message:  fmt.Sprintf(format, a...),
			Target:   fnv1.Target_TARGET_COMPOSITE.Enum(),
		}
	}

	const (
		dependency   = "cert-manager"
		component    = "gpu-operator"
		preObject    = "gpu-operator-pre-namespace-gpu-operator"
		postObject   = "gpu-operator-post-clusterpolicy-cluster-policy"
		manifestOnly = "nodewright-customizations"
		mOnlyObject  = "nodewright-customizations-post-configmap-tuning"
	)
	chart := func(name string, deps ...string) *recipe.ComponentRef {
		return &recipe.ComponentRef{Name: name, Type: recipe.ComponentTypeHelm, Source: "https://example.com", Chart: name, DependencyRefs: deps}
	}
	manifests := func(name string, deps ...string) *recipe.ComponentRef {
		return &recipe.ComponentRef{Name: name, Type: recipe.ComponentTypeHelm, ManifestFiles: []string{"post/tuning.yaml"}, DependencyRefs: deps}
	}

	// Component sets.
	componentWithDependency := map[string]*recipe.ComponentRef{
		dependency: chart(dependency),
		component:  chart(component, dependency),
	}
	componentWithUnmanagedDependency := map[string]*recipe.ComponentRef{
		component: chart(component, "nfd"),
	}
	componentAlone := map[string]*recipe.ComponentRef{
		component: chart(component),
	}
	componentOnManifestOnly := map[string]*recipe.ComponentRef{
		manifestOnly: manifests(manifestOnly),
		component:    chart(component, manifestOnly),
	}
	manifestOnlyWithDependency := map[string]*recipe.ComponentRef{
		dependency:   chart(dependency),
		manifestOnly: manifests(manifestOnly, dependency),
	}

	// Object sets.
	none := manifestObjects{}
	pre := manifestObjects{pre: map[string][]string{component: {preObject}}}
	post := manifestObjects{post: map[string][]string{component: {postObject}}}
	mOnly := manifestObjects{post: map[string][]string{manifestOnly: {mOnlyObject}}}

	type args struct {
		managed  map[string]*recipe.ComponentRef
		desired  []string
		observed map[resource.Name]resource.ObservedComposed
		objects  manifestObjects
	}
	type want struct {
		desired []string
		results []*fnv1.Result
	}

	cases := map[string]struct {
		reason string
		args   args
		want   want
	}{
		// Release ← managed dependencies.
		"GatesReleaseWhenDependencyAbsent": {
			reason: "Nothing observed: the dependent Release is withheld and the dependency survives.",
			args:   args{managed: componentWithDependency, desired: []string{dependency, component}, objects: none},
			want: want{
				desired: []string{dependency},
				results: []*fnv1.Result{delay(`delaying %q until dependency %q is ready`, component, dependency)},
			},
		},
		"GatesReleaseWhenDependencyNotReady": {
			reason: "The dependency is observed but not Ready: the dependent Release is still withheld.",
			args:   args{managed: componentWithDependency, desired: []string{dependency, component}, observed: observe(notReady(dependency)), objects: none},
			want: want{
				desired: []string{dependency},
				results: []*fnv1.Result{delay(`delaying %q until dependency %q is ready`, component, dependency)},
			},
		},
		"EmitsReleaseWhenDependencyReady": {
			reason: "The dependency is observed Ready: both Releases survive.",
			args:   args{managed: componentWithDependency, desired: []string{dependency, component}, observed: observe(ready(dependency)), objects: none},
			want:   want{desired: []string{dependency, component}},
		},
		"NeverDeletesLiveRelease": {
			reason: "The dependent is already live while its dependency is absent: the gate must not tear down a running component when its dependency goes briefly unready.",
			args:   args{managed: componentWithDependency, desired: []string{component}, observed: observe(ready(component)), objects: none},
			want:   want{desired: []string{component}},
		},
		"EmitsReleaseWhenDependencyUnmanaged": {
			reason: "A dependency absent from the managed set is treated as satisfied — the user opted to manage it elsewhere.",
			args:   args{managed: componentWithUnmanagedDependency, desired: []string{component}, objects: none},
			want:   want{desired: []string{component}},
		},

		// Release ← its pre-manifest Objects.
		"GatesReleaseWhenPreObjectAbsent": {
			reason: "Nothing observed: the Release is withheld and its pre-manifest Object stays in desired.",
			args:   args{managed: componentAlone, desired: []string{component, preObject}, objects: pre},
			want: want{
				desired: []string{preObject},
				results: []*fnv1.Result{delay(`delaying %q until pre-manifest object %q is ready`, component, preObject)},
			},
		},
		"GatesReleaseWhenPreObjectNotReady": {
			reason: "The pre-manifest Object is observed but not Ready: the Release is still withheld.",
			args:   args{managed: componentAlone, desired: []string{component, preObject}, observed: observe(notReady(preObject)), objects: pre},
			want: want{
				desired: []string{preObject},
				results: []*fnv1.Result{delay(`delaying %q until pre-manifest object %q is ready`, component, preObject)},
			},
		},
		"EmitsReleaseWhenPreObjectReady": {
			reason: "The pre-manifest Object is observed Ready: the Release survives.",
			args:   args{managed: componentAlone, desired: []string{component, preObject}, observed: observe(ready(preObject)), objects: pre},
			want:   want{desired: []string{component, preObject}},
		},
		"NeverDeletesLiveReleaseWhenPreObjectAbsent": {
			reason: "The Release is already live while its pre-manifest Object is absent: the gate must not tear down a running component when a sibling goes briefly unready.",
			args:   args{managed: componentAlone, desired: []string{component, preObject}, observed: observe(ready(component)), objects: pre},
			want:   want{desired: []string{component, preObject}},
		},

		// Pre-manifest Objects ← managed dependencies.
		"GatesPreObjectsAndReleaseWhenDependencyNotReady": {
			reason: "A component's pre-manifest Objects wait for its dependencies too: aicr's pre wave follows the dependencies' waves.",
			args:   args{managed: componentWithDependency, desired: []string{dependency, component, preObject}, objects: pre},
			want: want{
				desired: []string{dependency},
				results: []*fnv1.Result{
					delay(`delaying pre-manifest objects of %q until dependency %q is ready`, component, dependency),
					delay(`delaying %q until dependency %q is ready`, component, dependency),
				},
			},
		},
		"NeverDeletesLivePreObject": {
			reason: "The pre-manifest Object is already live while the dependency is absent: only the not-yet-created Release is withheld, and no pre-manifest delay is reported for nothing.",
			args:   args{managed: componentWithDependency, desired: []string{dependency, component, preObject}, observed: observe(ready(preObject)), objects: pre},
			want: want{
				desired: []string{dependency, preObject},
				results: []*fnv1.Result{delay(`delaying %q until dependency %q is ready`, component, dependency)},
			},
		},

		// Post-manifest Objects ← the component's Release.
		"GatesPostObjectsWhenReleaseAbsent": {
			reason: "The Release is not yet created: its post-manifest Objects are withheld (aicr's post wave lands after the chart).",
			args:   args{managed: componentAlone, desired: []string{component, postObject}, objects: post},
			want: want{
				desired: []string{component},
				results: []*fnv1.Result{delay(`delaying post-manifest objects of %q until its Release is ready`, component)},
			},
		},
		"GatesPostObjectsWhenReleaseNotReady": {
			reason: "The Release is observed but not Ready (still installing): its post-manifest Objects are still withheld.",
			args:   args{managed: componentAlone, desired: []string{component, postObject}, observed: observe(notReady(component)), objects: post},
			want: want{
				desired: []string{component},
				results: []*fnv1.Result{delay(`delaying post-manifest objects of %q until its Release is ready`, component)},
			},
		},
		"EmitsPostObjectsWhenReleaseReady": {
			reason: "The Release is observed Ready: its post-manifest Objects survive.",
			args:   args{managed: componentAlone, desired: []string{component, postObject}, observed: observe(ready(component)), objects: post},
			want:   want{desired: []string{component, postObject}},
		},
		"NeverDeletesLivePostObject": {
			reason: "The post-manifest Object is already live while its Release is not observed: the gate must not tear it down.",
			args:   args{managed: componentAlone, desired: []string{component, postObject}, observed: observe(ready(postObject)), objects: post},
			want:   want{desired: []string{component, postObject}},
		},

		// Manifest-only component's Objects ← managed dependencies.
		"GatesManifestOnlyObjectsWhenDependencyNotReady": {
			reason: "A manifest-only component has no Release, so all of its Objects wait for its dependencies.",
			args:   args{managed: manifestOnlyWithDependency, desired: []string{dependency, mOnlyObject}, objects: mOnly},
			want: want{
				desired: []string{dependency},
				results: []*fnv1.Result{delay(`delaying objects of %q until dependency %q is ready`, manifestOnly, dependency)},
			},
		},
		"EmitsManifestOnlyObjectsWhenDependencyReady": {
			reason: "The manifest-only component's dependency is observed Ready: its Objects survive.",
			args:   args{managed: manifestOnlyWithDependency, desired: []string{dependency, mOnlyObject}, observed: observe(ready(dependency)), objects: mOnly},
			want:   want{desired: []string{dependency, mOnlyObject}},
		},
		"NeverDeletesLiveManifestOnlyObject": {
			reason: "The manifest-only component's Object is already live while its dependency is absent: the gate must not tear it down.",
			args:   args{managed: manifestOnlyWithDependency, desired: []string{dependency, mOnlyObject}, observed: observe(ready(mOnlyObject)), objects: mOnly},
			want:   want{desired: []string{dependency, mOnlyObject}},
		},

		// Manifest-only component as a dependency: readiness is that of its Objects.
		"GatesDependentOnManifestOnlyDependencyWhoseObjectsAreNotReady": {
			reason: "The dependent's manifest-only dependency has an Object observed but not Ready: the dependent Release is withheld.",
			args:   args{managed: componentOnManifestOnly, desired: []string{component, mOnlyObject}, observed: observe(notReady(mOnlyObject)), objects: mOnly},
			want: want{
				desired: []string{mOnlyObject},
				results: []*fnv1.Result{delay(`delaying %q until dependency %q is ready`, component, manifestOnly)},
			},
		},
		"EmitsDependentWhenManifestOnlyDependencyObjectsReady": {
			reason: "No Release carries a manifest-only component's name, so a bare-name lookup would deadlock; its readiness is that of every Object it emitted.",
			args:   args{managed: componentOnManifestOnly, desired: []string{component, mOnlyObject}, observed: observe(ready(mOnlyObject)), objects: mOnly},
			want:   want{desired: []string{component, mOnlyObject}},
		},
		"EmitsDependentWhenManifestOnlyDependencyHasNoObjects": {
			reason: "The manifest-only dependency emitted no Objects at all: there is nothing to wait for.",
			args:   args{managed: componentOnManifestOnly, desired: []string{component}, objects: none},
			want:   want{desired: []string{component}},
		},
	}

	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			desired := make(map[resource.Name]*resource.DesiredComposed, len(tc.args.desired))
			for _, n := range tc.args.desired {
				desired[resource.Name(n)] = &resource.DesiredComposed{Resource: composed.New()}
			}
			rsp := &fnv1.RunFunctionResponse{}

			s := &stack{managed: tc.args.managed, desired: desired, observed: tc.args.observed, objects: tc.args.objects}
			s.gate(rsp)

			gotDesired := slices.Sorted(maps.Keys(desired))
			wantDesired := make([]resource.Name, 0, len(tc.want.desired))
			for _, n := range tc.want.desired {
				wantDesired = append(wantDesired, resource.Name(n))
			}
			slices.Sort(wantDesired)
			if diff := cmp.Diff(wantDesired, gotDesired); diff != "" {
				t.Errorf("%s\ngate(...): -want desired keys, +got desired keys:\n%s", tc.reason, diff)
			}
			if diff := cmp.Diff(tc.want.results, rsp.GetResults(), protocmp.Transform()); diff != "" {
				t.Errorf("%s\ngate(...): -want results, +got results:\n%s", tc.reason, diff)
			}
		})
	}
}

