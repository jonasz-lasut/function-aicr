// yamlToProto loads a single-document YAML fixture (relative to test-fixtures/)
// as a protobuf Struct. For test use only; panics on error.
func yamlToProto(name string) *structpb.Struct {
	y, err := os.ReadFile(filepath.Join(fixturesDir, name))
	if err != nil {
		panic(err)
	}
	j, err := sigsyaml.YAMLToJSON(y)
	if err != nil {
		panic(err)
	}
	return resource.MustStructJSON(string(j))
}

func fixture(name string) *fnv1.Resource { return &fnv1.Resource{Resource: yamlToProto(name)} }

// golden names the generated fixtures under test-fixtures/want that a case's
// desired state is compared against; either may be empty when the case is
// expected to produce none.
type golden struct {
	resources string // directory holding one <name>.yaml per desired composed resource
	composite string // file holding the desired composite resource
}

// loadGolden reads the desired state a case expects, or nil if it expects none.
func loadGolden(t *testing.T, g golden) *fnv1.State {
	t.Helper()
	if g.resources == "" && g.composite == "" {
		return nil
	}
	state := &fnv1.State{}
	if g.resources != "" {
		entries, err := os.ReadDir(filepath.Join(fixturesDir, wantDir, g.resources))
		if err != nil {
			t.Fatalf("cannot read golden resources %q (run `go generate ./...`): %v", g.resources, err)
		}
		state.Resources = make(map[string]*fnv1.Resource, len(entries))
		for _, e := range entries {
			name := strings.TrimSuffix(e.Name(), ".yaml")
			state.Resources[name] = fixture(filepath.Join(wantDir, g.resources, e.Name()))
		}
	}
	if g.composite != "" {
		state.Composite = fixture(filepath.Join(wantDir, g.composite))
	}
	return state
}

// writtenGolden guards against two cases regenerating the same golden file
// with different content, which check mode would otherwise report as a
// failure that `go generate` cannot fix.
var writtenGolden = map[string][]byte{}

// writeGolden regenerates the golden fixtures a case names from the desired
// state the function produced.
func writeGolden(t *testing.T, g golden, got *fnv1.State) {
	t.Helper()
	write := func(rel string, s *structpb.Struct) {
		j, err := protojson.Marshal(s)
		if err != nil {
			t.Fatalf("cannot marshal %q: %v", rel, err)
		}
		y, err := sigsyaml.JSONToYAML(j)
		if err != nil {
			t.Fatalf("cannot convert %q to YAML: %v", rel, err)
		}
		y = append([]byte(goldenHeader), y...)
		path := filepath.Join(fixturesDir, wantDir, rel)
		if prev, ok := writtenGolden[path]; ok && !slices.Equal(prev, y) {
			t.Fatalf("golden %q regenerated with different content by two cases; give them separate goldens", rel)
		}
		writtenGolden[path] = y
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("cannot create %q: %v", filepath.Dir(path), err)
		}
		if err := os.WriteFile(path, y, 0o644); err != nil {
			t.Fatalf("cannot write %q: %v", path, err)
		}
	}
	if len(got.GetResources()) > 0 && g.resources == "" {
		t.Fatalf("case produced %d desired resources but names no golden resources directory", len(got.GetResources()))
	}
	if got.GetComposite() != nil && g.composite == "" {
		t.Fatalf("case produced a desired composite but names no golden composite file")
	}
	for name, r := range got.GetResources() {
		write(filepath.Join(g.resources, name+".yaml"), r.GetResource())
	}
	if c := got.GetComposite(); c != nil {
		write(g.composite, c.GetResource())
	}
}

// permissiveSchema accepts any object. It proves the plumbing without pinning
// this test to provider-helm's real CRD; schema.Validate is tested separately.
func permissiveSchema() *fnv1.Schema {
	s, err := structpb.NewStruct(map[string]any{
		"type":                                 "object",
		"x-kubernetes-preserve-unknown-fields": true,
	})
	if err != nil {
		panic(err)
	}
	return &fnv1.Schema{OpenapiV3: s}
}

